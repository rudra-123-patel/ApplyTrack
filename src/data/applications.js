// Dynamically calculate monthly application activity directly from application data
export function calculateMonthlyActivity(applications) {
  const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  
  if (!applications || applications.length === 0) {
    return [];
  }

  const monthMap = {};

  applications.forEach((app) => {
    if (!app.appliedDate) return;
    const parts = app.appliedDate.split('-');
    if (parts.length < 2) return;
    
    const year = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10) - 1;
    
    if (isNaN(year) || isNaN(month) || month < 0 || month > 11) return;
    
    const sortKey = `${year}-${String(month + 1).padStart(2, '0')}`;
    const label = monthNames[month];

    if (!monthMap[sortKey]) {
      monthMap[sortKey] = {
        month: label,
        applications: 0,
        interviews: 0,
        sortKey
      };
    }

    monthMap[sortKey].applications += 1;
    if (app.status === 'Interview') {
      monthMap[sortKey].interviews += 1;
    }
  });

  const sortedKeys = Object.keys(monthMap).sort();
  if (sortedKeys.length === 0) {
    return [];
  }

  // Return up to the latest 6 months of data
  return sortedKeys.slice(-6).map((k) => ({
    month: monthMap[k].month,
    applications: monthMap[k].applications,
    interviews: monthMap[k].interviews
  }));
}

